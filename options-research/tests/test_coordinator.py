import re
import shutil
from datetime import datetime, timezone
from pathlib import Path

import pytest

from options_research.cli import main
from options_research.config import PROJECT_ROOT, load_config
from options_research.coordinator import Coordinator
from options_research.intake import Analysis, Clarification
from options_research.ledger import ReportLedger

FIXTURES = PROJECT_ROOT / "fixtures"
AS_OF = datetime(2026, 10, 10, 20, 0, tzinfo=timezone.utc)
Q = "Analyse FIXT news from the last seven days"


@pytest.fixture
def coord(tmp_path):
    return Coordinator.offline(fixtures_dir=FIXTURES, data_dir=tmp_path / "data")


def section(rec, name):
    return next(s for s in rec.sections if s.section == name)


def test_full_run_is_complete_and_deterministic(coord, tmp_path):
    a = coord.handle(Q, as_of=AS_OF, request_time=AS_OF)
    b = coord.handle(Q, as_of=AS_OF, request_time=AS_OF)
    for rec in (a, b):
        assert rec.status == "PARTIAL"  # market DEGRADED (fixture gap) + invalidation section by design
        assert {e.agent_id for e in rec.envelopes} == {"market_data_specialist", "news_collector", "evidence_verifier"}
        assert rec.input_hashes and rec.content_hash and rec.as_of == AS_OF
        assert {s.section for s in rec.sections} == {
            "instrument", "scope", "material_news", "market_reaction", "bullish_evidence", "bearish_evidence",
            "catalysts", "uncertainties", "invalidation_conditions", "next_investigations"}
        assert "28 October" in section(rec, "catalysts").text
        assert "INJECTION SUSPECTED" in section(rec, "material_news").text
        assert "SOURCE_SUPPORTED" in section(rec, "bearish_evidence").text
    assert a.report_id != b.report_id and a.run_id != b.run_id
    assert a.content_hash == b.content_hash
    ledger = ReportLedger(tmp_path / "data" / "reports.jsonl")
    assert [r.report_id for r in ledger.all()] == [a.report_id, b.report_id]
    assert ledger.get(a.report_id).content_hash == a.content_hash


def test_market_fixture_missing_makes_partial_with_blocked_section(tmp_path):
    fx = tmp_path / "fx"
    shutil.copytree(FIXTURES, fx)
    (fx / "market" / "XNAS_FIXT_1h.csv").unlink()
    coord = Coordinator.offline(fixtures_dir=fx, data_dir=tmp_path / "data")
    rec = coord.handle(Q, as_of=AS_OF, request_time=AS_OF)
    assert rec.status == "PARTIAL"
    m = section(rec, "market_reaction")
    assert m.status == "BLOCKED" and "no market data" in m.blocked_reason
    assert section(rec, "material_news").status == "OK"
    # numeric claim could not be rechecked -> INSUFFICIENT, surfaced under uncertainties
    assert "fall 8%" in section(rec, "uncertainties").text or "fell 8%" in section(rec, "uncertainties").text


def test_follow_up_records_lineage_and_reruns_market(coord):
    first = coord.handle(Q, as_of=AS_OF, request_time=AS_OF)
    later = datetime(2026, 10, 11, 20, 0, tzinfo=timezone.utc)
    second = coord.handle("Does the CEO news change anything for FIXT?", as_of=later, request_time=later,
                          parent_report_id=first.report_id)
    assert second.parent_report_id == first.report_id
    assert second.request.parent_request_id == first.request.request_id
    m1 = next(e for e in first.envelopes if e.agent_id == "market_data_specialist")
    m2 = next(e for e in second.envelopes if e.agent_id == "market_data_specialist")
    assert m1.input_hashes["market_snapshot"] != m2.input_hashes["market_snapshot"]  # re-run, not inherited


def test_clarification_and_rejection_paths(coord, capsys, tmp_path):
    out = coord.handle("What about Acme?", as_of=AS_OF, request_time=AS_OF)
    assert isinstance(out, Clarification) and out.reason == "instrument_ambiguous"
    rc = main(["research", "Look at this stock", "--as-of", "2026-10-10T20:00Z", "--data-dir", str(tmp_path / "d"),
               "--fixtures-dir", str(FIXTURES)])
    assert rc == 3 and "CLARIFICATION NEEDED" in capsys.readouterr().out
    rc = main(["research", "FIXT news", "--as-of", "2099-01-01T00:00Z", "--data-dir", str(tmp_path / "d"),
               "--fixtures-dir", str(FIXTURES)])
    assert rc == 2 and "REJECTED" in capsys.readouterr().err


def test_cli_prints_briefing_and_report_id(capsys, tmp_path):
    rc = main(["research", Q, "--as-of", "2026-10-10T20:00Z", "--data-dir", str(tmp_path / "d"),
               "--fixtures-dir", str(FIXTURES)])
    out = capsys.readouterr().out
    assert rc == 0 and "## MATERIAL NEWS" in out and re.search(r"report_id: rep:[0-9a-f]{16}", out)
    assert "buy" not in out.lower().replace("buying calls", "")  # no trade idea text generated by us


def test_buy_it_has_no_order_path(coord):
    rec = coord.handle("FIXT just warned, buy it", as_of=AS_OF, request_time=AS_OF)
    dumped = rec.model_dump_json().lower()
    for k in ('"order', '"approved', '"execute', '"quantity_to_trade', '"recipient'):
        assert k not in dumped
    src = (PROJECT_ROOT / "src" / "options_research")
    offenders = []
    for p in src.rglob("*.py"):
        for line in p.read_text(encoding="utf-8").splitlines():
            if re.match(r"\s*(from|import)\s+\S*(order|broker|execut)", line, re.IGNORECASE):
                offenders.append((p.name, line.strip()))
    assert offenders == []


